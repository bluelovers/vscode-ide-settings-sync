/**
 * 清除搜尋輸入框的文字與搜尋結果
 * Clear the search input text and search results
 *
 * 同時儲存清空後的搜尋字串至 globalState。
 * Also saves the cleared search string to globalState.
 */
export function clearSearch(): void
{
	/**
	 * 更新 searchQuery signal，SearchResultsList 組件自動清空
	 * Update searchQuery signal; SearchResultsList component clears automatically
	 *
	 * 為什麼要保存到歷史：清除搜尋後需要記錄這次操作，以便後續可以恢復或追蹤使用模式
	 * Why save to history: After clearing search, need to record this operation for recovery or usage pattern tracking
	 */
	searchQuery.value = '';
	saveSearchHistory();
}

/**
 * 從已儲存的選取設定列表中移除單一設定 key
 * Remove a single setting key from the saved selected settings list
 *
 * @param key - 要移除的點分隔 VS Code 設定 key / Dot-separated VS Code setting key to remove
 */
export function removeFromSelectedSettings(key: string): void
{
	const state = getState();
	/**
	 * 從全局狀態取得已儲存的選取設定列表
	 * Get saved selected settings list from global state
	 *
	 * 為什麼從 state 讀取而非 signal：這是持久化儲存，需要同步到 Extension host
	 * Why read from state instead of signal: This is persisted storage, needs sync to Extension host
	 */
	const savedSelectedSettings: string[] = state.savedSelectedSettings ?? [];
	const index = savedSelectedSettings.indexOf(key);
	/**
	 * 找到後從陣列中移除，並同步至 Extension host 的 globalState
	 * If found, remove from array and sync to Extension host's globalState
	 *
	 * 為什麼要同步兩個地方：savedSelectedSettings 是持久化儲存，checkedSettingKeys 是響應式狀態
	 * 兩者需要保持一致，否則UI顯示和實際儲存會不符
	 * Why sync two places: savedSelectedSettings is persisted storage, checkedSettingKeys is reactive state
	 * Both need to stay consistent, otherwise UI display and actual storage will mismatch
	 */
	if (index > -1)
	{
		savedSelectedSettings.splice(index, 1);
		vscode.postMessage({ command: EnumWebviewCommand.SaveSelectedSettings, selectedSettings: savedSelectedSettings });
		/**
		 * 更新 checkedSettingKeys signal，SelectedSettingsList 組件自動重新渲染
		 * Update checkedSettingKeys signal; SelectedSettingsList component re-renders automatically
		 *
		 * 為什麼要更新 signal：確保UI立即反映變更，而不需要等待Extension host的回應
		 * Why update signal: Ensure UI reflects changes immediately without waiting for Extension host response
		 */
		const next = new Set(checkedSettingKeys.value);
		next.delete(key);
		checkedSettingKeys.value = next;
		showMessage(`✓ Removed "${key}" from selected settings`, EnumShowMessageType.SUCCESS);
	}
}

/**
 * 在使用者確認後清除所有已儲存的選取設定
 * Clear all saved selected settings after user confirmation
 */
export function clearAllSelectedSettings(): void
{
	/**
	 * 請求使用者確認是否清除所有選取設定
	 * Request user confirmation before clearing all selected settings
	 *
	 * 為什麼需要確認：清除所有選取設定是破壞性操作，需要防止誤操作
	 * Why confirmation needed: Clearing all selected settings is destructive, prevents accidental operations
	 */
	if (confirm('Clear all selected settings?'))
	{
		const state = getState();
		/**
		 * 清空陣列並同步至 Extension host 的 globalState
		 * Clear the array and sync to Extension host's globalState
		 *
		 * 為什麼要同時更新兩處：確保持久化儲存和記憶體狀態都清空
		 * Why update both places: Ensure both persisted storage and in-memory state are cleared
		 */
		state.savedSelectedSettings = [];
		vscode.postMessage({ command: EnumWebviewCommand.SaveSelectedSettings, selectedSettings: [] });
		/**
		 * 清空 checkedSettingKeys signal，SelectedSettingsList 組件自動重新渲染
		 * Clear checkedSettingKeys signal; SelectedSettingsList component re-renders automatically
		 *
		 * 為什麼要清空 signal：確保UI立即清空，提供即時反饋
		 * Why clear signal: Ensure UI clears immediately, providing instant feedback
		 */
		checkedSettingKeys.value = new Set();
		showMessage('✓ All selected settings cleared', EnumShowMessageType.SUCCESS);
	}
}

/**
 * 請求 Extension host 重新載入設定資料並重繪 Webview
 * Request the Extension host to reload settings data and redraw the Webview
 *
 * 為什麼需要重新載入：設定可能在其他 IDE 中被修改，需要獲取最新狀態
 * 重新載入會從 Extension host 重新取得所有設定並重新渲染整個 Webview
 * Why reload needed: Settings may be modified in other IDEs, need to get latest state
 * Reloading fetches all settings from Extension host and re-renders entire Webview
 */
export function refreshSettings(): void
{
	vscode.postMessage({ command: EnumWebviewCommand.RefreshData });
	showMessage('⟳ Settings refreshed', EnumShowMessageType.INFO);
}
