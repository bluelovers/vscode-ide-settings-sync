/**
 * 取得注入的初始狀態物件的便捷存取器
 * Convenience accessor for the injected initial state object
 *
 * 使用 `?? {}` fallback 確保在狀態尚未注入時不會拋出例外。
 * Uses `?? {}` fallback to ensure no exception is thrown when state has not yet been injected.
 *
 * 為什麼需要此函數：初始狀態由 Extension host 透過 SSR 注入至 window 物件，
 * 提供統一的存取點避免重複的型別斷言與 null 檢查。
 * Why this function is needed: Initial state is injected to window object by Extension host via SSR,
 * provides unified access point to avoid repetitive type assertions and null checks.
 */
function getState(): IWebviewState
{
	return (window as any as IWebviewWindow).__INITIAL_STATE__ ?? {};
}

/** ─── 描述查找輔助函數 / Description lookup helpers ─── */

/**
 * 查找設定 key 對應的人類可讀描述字串
 * Look up the human-readable description string for a setting key
 *
 * 描述來自 `__INITIAL_STATE__.settingDescriptions`，
 * 由 Extension host 根據當前語言配置預先產生。
 * 若有副語言描述，會以 `<small>` 標籤附加在主語言描述後。
 *
 * Descriptions come from `__INITIAL_STATE__.settingDescriptions`,
 * pre-generated by the Extension host based on current language config.
 * If a secondary language description exists, it is appended after the primary description in a `<small>` tag.
 *
 * 為什麼描述由 Extension host 預先產生：
 * 設定描述需要根據當前語言動態取得，在 Node.js 端處理更有效率，
 * 避免在前端動態載入大量語言檔案。
 * Why descriptions are pre-generated by Extension host:
 * Setting descriptions need to be dynamically fetched based on current language,
 * processing on Node.js side is more efficient, avoiding loading large language files on frontend.
 *
 * @param key - 點分隔的 VS Code 設定 key / Dot-separated VS Code setting key
 * @returns 包含 HTML 標記的描述字串，找不到時回傳預設文字 / Description string with HTML markup, returns default text if not found
 */
export function getSettingDescription(key: string): string
{
	/**
	 * 從全局狀態中取得設定描述對照表
	 * Get setting description mapping from global state
	 *
	 * 為什麼使用 ?? {} fallback：確保在狀態尚未注入時不會拋出型別錯誤
	 * Why use ?? {} fallback: Ensures no type errors when state hasn't been injected yet
	 */
	const descriptions: Record<string, { primary: string; secondary?: string }> =
		getState().settingDescriptions ?? {};
	const desc = descriptions[key];
	/**
	 * 找不到描述時回傳預設文字
	 * Return default text when description not found
	 *
	 * 為什麼需要 fallback：部分設定可能沒有描述，不應該顯示空白或拋出錯誤
	 * Why fallback needed: Some settings may not have descriptions, shouldn't show blank or throw errors
	 */
	if (!desc) return 'No description available';
	/**
	 * 若有副語言描述，以斜體小字附加在主語言描述後
	 * If secondary language description exists, append it after the primary description in italic small text
	 *
	 * 為什麼使用 <small> 標籤：副語言描述作為補充資訊，視覺上應該較不突顯
	 * Why use <small> tag: Secondary language description is supplementary info, visually less prominent
	 */
	if (desc.secondary)
	{
		return `${desc.primary}<br/><small style="color: #999; font-style: italic;">(${desc.secondary})</small>`;
	}
	return desc.primary || 'No description available';
}

