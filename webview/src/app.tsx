	cspSource: string;
	/** Webview bundle 的 URI（由 VS Code Webview API 產生）/ URI of the Webview bundle (generated by VS Code Webview API) */
	webviewScriptUri: string;
	/** 注入至 `window.__INITIAL_STATE__` 的初始狀態物件 / Initial state object injected into `window.__INITIAL_STATE__` */
	initialState: IWebviewState;
